// Isolated Postgres/PGlite acceptance. No URL, credentials or remote connection.
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {contactFingerprint} from '../lib/control/commercial-inbox.mjs';
const modulePath=process.argv[2];
if(!modulePath)throw Error('Indicá el módulo PGlite temporal, no una URL de base de datos.');
const {PGlite}=await import(pathToFileURL(modulePath)),db=new PGlite();
const admin=randomUUID(),editor=randomUUID(),reader=randomUUID(),session=randomUUID(),adminSession=randomUUID(),readerSession=randomUUID();
const payload={institutionName:'Institución aislada',name:'Persona prueba',phone:'3810000000',email:'test@example.invalid',plan:'Básico',message:'Prueba SQL aislada'};
const key=randomUUID(),fingerprint=contactFingerprint(payload),rate='a'.repeat(64);
try {
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
    create schema auth;create schema storage;
    create table auth.users(id uuid primary key,email_confirmed_at timestamptz,is_anonymous boolean,banned_until timestamptz);
    create table auth.sessions(id uuid,user_id uuid,not_after timestamptz);
    create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
    create function auth.uid() returns uuid language sql stable as $$select (auth.jwt()->>'sub')::uuid$$;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit int,allowed_mime_types text[]);
    grant usage on schema auth to authenticated;
    grant usage on schema public to service_role,anon,authenticated;`);
  const baseline=process.argv[3] ? pathToFileURL(process.argv[3]) : new URL('../../docs/control/instalar-en-staging.sql',import.meta.url);
  await db.exec(await readFile(baseline,'utf8'));
  await db.query('insert into auth.users values($1,now(),false,null),($2,now(),false,null),($3,now(),false,null)',[admin,editor,reader]);
  await db.query('insert into auth.sessions values($1,$2,null),($3,$4,null),($5,$6,null)',[session,editor,adminSession,admin,readerSession,reader]);
  await db.query("insert into public.get_control_members values($1,'Admin','ADMINISTRADOR',true),($2,'Editor','EDITOR',true),($3,'Lector','LECTOR',true)",[admin,editor,reader]);
  await db.exec(await readFile(new URL('../docs/control/COMMERCIAL-INBOX.sql',import.meta.url),'utf8'));
  const receive=(id=key,body=payload)=>db.query('select public.get_commercial_contact_receive($1,$2,$3,$4) as result',[id,contactFingerprint(body),JSON.stringify(body),rate]);
  await db.exec('set role anon');
  await assert.rejects(receive());await assert.rejects(db.query('select * from public.get_commercial_contacts'));
  await db.exec('set role service_role');
  const first=(await receive(key,{...payload,source_path:'/admin',sourcePath:'https://malicious.example'})).rows[0].result;assert.equal(first.status,201);
  assert.deepEqual((await receive()).rows[0].result,first);
  assert.equal((await receive(key,{...payload,name:'Otra persona'})).rows[0].result.status,409);
  for(let i=0;i<4;i++)assert.equal((await receive(randomUUID())).rows[0].result.status,201);
  assert.equal((await receive(randomUUID())).rows[0].result.status,429);
  await db.exec('set role authenticated');
  const identify=(id,override)=>db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:id,session_id:override||(id===admin?adminSession:id===reader?readerSession:session)})]);
  const list=()=>db.query("select public.get_commercial_contact_list('','',1) as result");
  await identify(reader);await assert.rejects(list());assert.equal((await db.query('select id,email from public.get_commercial_contacts')).rows.length,0);
  await identify(editor);await assert.rejects(receive());
  const result=(await list()).rows[0].result;assert.equal(result.total,5);assert.equal('fingerprint' in result.rows[0],false);
  assert.ok(result.rows.every(row=>row.source_path==='/contacto'));
  await assert.rejects(db.query('select fingerprint from public.get_commercial_contacts'));
  await assert.rejects(db.query("update public.get_commercial_contacts set email='bad@example.invalid' where id=$1",[first.receiptId]));
  await assert.rejects(db.query("update public.get_commercial_contacts set source_path='/otro' where id=$1",[first.receiptId]));
  const update=(revision,status='en_seguimiento')=>db.query('select public.get_commercial_contact_status($1,$2,$3) as result',[first.receiptId,status,revision]);
  assert.equal((await update(0)).rows[0].result.revision,1);
  await assert.rejects(update(0,'cerrada'));
  assert.equal((await db.query('select * from public.get_commercial_contact_audit')).rows.length,1);
  await assert.rejects(db.query('delete from public.get_commercial_contacts where id=$1',[first.receiptId]));
  await identify(admin);assert.equal((await update(1,'cerrada')).rows[0].result.revision,2);
  await identify(editor,randomUUID());await assert.rejects(list());await assert.rejects(update(2));
  await db.exec('reset role');await db.query('update public.get_control_members set active=false where id=$1',[editor]);
  await db.exec('set role authenticated');await identify(editor);await assert.rejects(list());await assert.rejects(update(2));
  console.log('PASS isolated SQL: atomic install, durable receipt, duplicate/conflict, distributed rate, anon/LECTOR/inactive denied, editor/admin, column protection, CAS, audit, no public PII.');
} finally {await db.close();}
